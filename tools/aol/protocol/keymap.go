// USB HID Usage Page 0x07 modifier usages used by hotkey checks.
const (
	HIDLeftCtrl   uint16 = 0xE0
	HIDLeftShift  uint16 = 0xE1
	HIDLeftAlt    uint16 = 0xE2
	HIDLeftGUI    uint16 = 0xE3
	HIDRightCtrl  uint16 = 0xE4
	HIDRightShift uint16 = 0xE5
	HIDRightAlt   uint16 = 0xE6
	HIDRightGUI   uint16 = 0xE7
	HIDKeyG       uint16 = 0x0A
)

// LinuxEvdevToHID translates a Linux evdev key code (KEY_*) to a USB HID
// Usage Page 0x07 usage code, returning 0 when unmapped.
func LinuxEvdevToHID(code uint16) uint16 {
	if int(code) < len(linuxEvdevHID) {
		return linuxEvdevHID[code]
	}
	return 0
}

// WindowsScancodeToHID translates a Windows PS/2 Set-1 raw input scan code
// (and E0 extended flag) to a USB HID Usage Page 0x07 usage code.
func WindowsScancodeToHID(makeCode uint16, extended bool) uint16 {
	if extended {
		if int(makeCode) < len(winExtScancodeHID) {
			return winExtScancodeHID[makeCode]
		}
		return 0
	}
	if int(makeCode) < len(winBaseScancodeHID) {
		return winBaseScancodeHID[makeCode]
	}
	return 0
}

